import Charts
import SwiftUI

/// The fixed US-Letter frame every report page renders in. Print output is
/// always light mode on white.
struct ReportPageFrame<Content: View>: View {

  @ViewBuilder let content: () -> Content

  var body: some View {
    content()
      .padding(40)
      .frame(width: ClinicianReportBuilder.pageSize.width, height: ClinicianReportBuilder.pageSize.height, alignment: .top)
      .background(Color.white)
      .environment(\.colorScheme, .light)
  }

}

/// A page's title header.
struct ReportHeader: View {

  let title: String
  let subtitle: String

  var body: some View {
    VStack(alignment: .leading, spacing: 2) {
      Text(title)
        .font(.title2.bold())
      Text(subtitle)
        .font(.caption)
        .foregroundColor(.secondary)
      Divider()
    }
  }

}

// MARK: - Summary page

/// The first page: key numbers plus frequency and severity charts.
struct ReportSummaryPage: View {

  let data: ClinicianReportData

  private var rangeText: String {
    let formatter = DateFormatter()
    formatter.dateStyle = .medium
    return "\(formatter.string(from: data.interval.start)) – \(formatter.string(from: data.interval.end)) · generated \(formatter.string(from: data.generatedAt))"
  }

  var body: some View {
    VStack(alignment: .leading, spacing: 20) {
      ReportHeader(title: "Headache Report", subtitle: rangeText)

      // Key numbers
      HStack(spacing: 12) {
        statBox(value: "\(data.headacheCount)", label: "Headaches")
        statBox(value: "\(data.daysWithHeadache)", label: "Days affected")
        statBox(value: Formatters.formatInterval(data.averageDuration), label: "Avg. duration")
      }

      if data.headacheCount == 0 {
        Spacer()
        Text("No headaches were logged in this period.")
          .font(.callout)
          .foregroundColor(.secondary)
          .frame(maxWidth: .infinity, alignment: .center)
        Spacer()
      }
      else {
        // Frequency by month
        VStack(alignment: .leading, spacing: 6) {
          Text("Headaches per month")
            .font(.headline)
          Chart(data.monthlyCounts) { item in
            BarMark(
              x: .value("Month", item.month, unit: .month),
              y: .value("Headaches", item.count))
            .foregroundStyle(Color.blue)
          }
          .frame(height: 180)
        }

        // Severity distribution
        VStack(alignment: .leading, spacing: 6) {
          Text("Peak severity distribution")
            .font(.headline)
          Chart(data.severityCounts) { item in
            BarMark(
              x: .value("Severity", item.severity.title),
              y: .value("Headaches", item.count))
            .foregroundStyle(Color.orange)
          }
          .frame(height: 180)
        }

        Spacer()
      }

      Text("Generated by Headache Tracker. Patterns shown are observational.")
        .font(.caption2)
        .foregroundColor(.secondary)
    }
  }

  private func statBox(value: String, label: String) -> some View {
    VStack(spacing: 4) {
      Text(value)
        .font(.title3.bold())
      Text(label)
        .font(.caption)
        .foregroundColor(.secondary)
    }
    .frame(maxWidth: .infinity)
    .padding(.vertical, 12)
    .background(RoundedRectangle(cornerRadius: 8).fill(Color(white: 0.95)))
  }

}

// MARK: - Log page

/// A paginated chunk of the headache log table.
struct ReportLogPage: View {

  let rows: [ClinicianReportData.HeadacheRow]
  let pageIndex: Int
  let pageCount: Int

  private static let dateFormatter: DateFormatter = {
    let formatter = DateFormatter()
    formatter.dateStyle = .short
    formatter.timeStyle = .short
    return formatter
  }()

  var body: some View {
    VStack(alignment: .leading, spacing: 12) {
      ReportHeader(title: "Headache Log", subtitle: "Page \(pageIndex) of \(pageCount)")

      Grid(alignment: .leading, horizontalSpacing: 10, verticalSpacing: 5) {
        GridRow {
          Text("Onset").bold()
          Text("Type").bold()
          Text("Peak").bold()
          Text("Duration").bold()
          Text("Medications").bold()
        }
        .font(.caption)

        Divider()

        ForEach(rows) { row in
          GridRow(alignment: .top) {
            Text(Self.dateFormatter.string(from: row.start))
            Text(row.type)
            Text(row.peakSeverity.title)
            // An unresolved headache has no end yet — its duration is only
            // "so far", so label it rather than print a misleading interval.
            Text(row.end == nil ? "ongoing" : Formatters.formatInterval(row.duration))
            Text(row.medications.isEmpty ? "—" : row.medications.joined(separator: ", "))
              .lineLimit(2)
          }
          .font(.caption)
        }
      }

      Spacer()
    }
  }

}

// MARK: - Insights page

/// Insights and medications.
struct ReportInsightsPage: View {

  let data: ClinicianReportData

  var body: some View {
    VStack(alignment: .leading, spacing: 16) {
      ReportHeader(title: "Patterns & Treatments", subtitle: "Correlations from the patient's own logs")

      if data.insights.isEmpty {
        Text("Not enough data yet for statistically supported correlations.")
          .font(.callout)
          .foregroundColor(.secondary)
      }
      else {
        VStack(alignment: .leading, spacing: 8) {
          Text("Correlated signals")
            .font(.headline)

          ForEach(data.insights) { insight in
            VStack(alignment: .leading, spacing: 1) {
              HStack {
                Text(insight.description)
                  .font(.caption)
                Spacer()
                Text("r = \(String(format: "%.2f", insight.coefficient)) · \(insight.confidence)")
                  .font(.caption2)
                  .foregroundColor(.secondary)
              }
              if let explainedBy = insight.explainedBy {
                Text("May be explained by \(explainedBy.lowercased()).")
                  .font(.caption2)
                  .foregroundColor(.secondary)
              }
            }
          }

          Text("Correlation is not causation: these associations come from observational self-tracked data and may reflect confounding.")
            .font(.caption2)
            .foregroundColor(.secondary)
            .padding(.top, 2)
        }
      }

      if !data.medications.isEmpty {
        VStack(alignment: .leading, spacing: 8) {
          Text("Medications")
            .font(.headline)

          Grid(alignment: .leading, horizontalSpacing: 10, verticalSpacing: 4) {
            GridRow {
              Text("Name").bold()
              Text("Times taken").bold()
              Text("Rated helpful").bold()
            }
            .font(.caption)

            Divider()

            ForEach(data.medications) { medication in
              GridRow {
                Text(medication.name)
                Text("\(medication.count)")
                Text(medication.ratedCount > 0 ? "\(medication.helpfulCount)/\(medication.ratedCount)" : "unrated")
              }
              .font(.caption)
            }
          }
        }
      }

      Spacer()
    }
  }

}
